BEGIN;

DO $$
BEGIN
    IF current_database() <> 'jolijob_db' OR current_user <> 'admin' THEN
        RAISE EXCEPTION 'Connect to jolijob_db as admin before running this script';
    END IF;
END
$$;

CREATE SCHEMA IF NOT EXISTS profiles AUTHORIZATION admin;
CREATE SCHEMA IF NOT EXISTS joboffers AUTHORIZATION admin;
CREATE SCHEMA IF NOT EXISTS applications AUTHORIZATION admin;
CREATE SCHEMA IF NOT EXISTS keycloak AUTHORIZATION admin;

CREATE TABLE IF NOT EXISTS profiles.candidates (
    id uuid PRIMARY KEY,
    user_id uuid NOT NULL UNIQUE,
    first_name varchar(255) NOT NULL,
    last_name varchar(255) NOT NULL,
    phone varchar(255),
    city varchar(255),
    country varchar(255),
    job_title varchar(255),
    summary varchar(255),
    cv_url varchar(255),
    linkedin_url varchar(255),
    portfolio_url varchar(255),
    birth_date date,
    open_to_remote boolean NOT NULL,
    open_to_relocation boolean NOT NULL,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);

CREATE TABLE IF NOT EXISTS profiles.companies (
    id uuid PRIMARY KEY,
    user_id uuid NOT NULL UNIQUE,
    name varchar(255) NOT NULL,
    siret varchar(255),
    description varchar(255),
    website varchar(255),
    sector varchar(255),
    country varchar(255),
    city varchar(255),
    logo_url varchar(255),
    contact_email varchar(255),
    contact_phone varchar(255),
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);

CREATE TABLE IF NOT EXISTS joboffers.job_offers (
    id uuid PRIMARY KEY,
    company_id uuid NOT NULL,
    company_name varchar(255),
    title varchar(255) NOT NULL,
    description text,
    job_category varchar(255),
    specialty varchar(255),
    contract_type varchar(255) NOT NULL
        CHECK (contract_type IN ('CDI', 'CDD', 'FREELANCE', 'INTERIM', 'STAGE', 'ALTERNANCE', 'VIE')),
    remote boolean NOT NULL,
    country varchar(255),
    region varchar(255),
    department varchar(255),
    city varchar(255),
    salary_min numeric(38, 2),
    salary_max numeric(38, 2),
    start_date date,
    expires_at date,
    active boolean NOT NULL,
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);

CREATE INDEX IF NOT EXISTS idx_job_offers_company ON joboffers.job_offers (company_id);

CREATE TABLE IF NOT EXISTS joboffers.job_offer_outbox (
    event_order bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL UNIQUE,
    aggregate_id uuid NOT NULL,
    topic varchar(255) NOT NULL,
    payload text NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    published_at timestamp(6) with time zone
);

CREATE INDEX IF NOT EXISTS idx_job_offer_outbox_aggregate_order
    ON joboffers.job_offer_outbox (aggregate_id, event_order);
CREATE INDEX IF NOT EXISTS idx_job_offer_outbox_pending
    ON joboffers.job_offer_outbox (published_at, event_order);

CREATE TABLE IF NOT EXISTS applications.applications (
    id uuid PRIMARY KEY,
    job_offer_id uuid NOT NULL,
    candidate_id uuid NOT NULL,
    candidate_email varchar(255),
    company_email varchar(255),
    job_title varchar(255),
    company_id uuid,
    cover_letter text,
    cv_url varchar(255),
    status varchar(255) NOT NULL
        CHECK (status IN ('SUBMITTED', 'VIEWED', 'SHORTLISTED', 'INTERVIEW_SCHEDULED',
                          'OFFER_MADE', 'ACCEPTED', 'REJECTED', 'WITHDRAWN')),
    submitted_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_application_offer_candidate UNIQUE (job_offer_id, candidate_id)
);

CREATE INDEX IF NOT EXISTS idx_applications_candidate
    ON applications.applications (candidate_id);
CREATE INDEX IF NOT EXISTS idx_applications_company
    ON applications.applications (company_id);

CREATE TABLE IF NOT EXISTS applications.application_outbox (
    sequence_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id varchar(36) NOT NULL UNIQUE,
    aggregate_id varchar(36) NOT NULL,
    payload text NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    published_at timestamp(6) with time zone,
    attempt_count integer NOT NULL,
    next_attempt_at timestamp(6) with time zone NOT NULL,
    last_error text
);

CREATE INDEX IF NOT EXISTS idx_application_outbox_pending
    ON applications.application_outbox (published_at, next_attempt_at, sequence_id);
CREATE INDEX IF NOT EXISTS idx_application_outbox_aggregate_order
    ON applications.application_outbox (aggregate_id, published_at, sequence_id);

-- Cross-service references remain logical; outbox rows must survive aggregate deletion.
COMMENT ON COLUMN joboffers.job_offers.company_id
    IS 'Logical reference to profiles.companies.id, resolved by HTTP by the service';
COMMENT ON COLUMN applications.applications.candidate_id
    IS 'Logical reference to profiles.candidates.id';
COMMENT ON COLUMN applications.applications.job_offer_id
    IS 'Logical reference to joboffers.job_offers.id';
COMMENT ON COLUMN applications.applications.company_id
    IS 'Company snapshot: logical reference to profiles.companies.id';
COMMENT ON COLUMN profiles.candidates.user_id
    IS 'Verified Keycloak subject (sub); not a foreign key into Keycloak tables';
COMMENT ON COLUMN profiles.companies.user_id
    IS 'Verified Keycloak subject (sub); not a foreign key into Keycloak tables';
COMMENT ON SCHEMA keycloak
    IS 'Tables managed exclusively by Keycloak migrations';

COMMIT;
